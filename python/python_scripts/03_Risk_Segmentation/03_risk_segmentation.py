#   Missing Current_DPD   -> Unresolved
#   Current_DPD = 0       -> Current
#   Current_DPD 1-30      -> 1-30
#   Current_DPD 31-60     -> 31-60
#   Current_DPD 61-90     -> 61-90
#   Current_DPD > 90      -> 90+
#   Other values          -> Invalid DPD
